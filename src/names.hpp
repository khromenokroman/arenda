#pragma once
#include <string>
#include <string_view>

/**
 * @brief Склонение в родительный падеж по правилам русского языка и сокращение ФИО.
 *
 * Результат склонения - черновик: правила верны для распространённых фамилий, имён и должностей,
 * но не знают исключений. Пользователь проверяет его в карточке.
 */
namespace names {

/**
 * @brief Пол по отчеству: «-ич», «оглы» - мужской, «-на», «кызы» - женский.
 * @return 'm', 'f' или 0, если отчества нет или оно не распознано
 */
[[nodiscard]] char gender_by_patronymic(std::string_view full_name);

/**
 * @brief ФИО «Фамилия Имя Отчество» в родительном падеже: «Иванов Иван Иванович» -> «Иванова Ивана Ивановича».
 * @param gender 'm' или 'f'; 0 - определить по отчеству, не удалось - мужской
 */
[[nodiscard]] std::string full_name_genitive(std::string_view full_name, char gender = 0);

/**
 * @brief Должность в родительном падеже: «Генеральный директор» -> «генерального директора».
 *
 * Склоняются прилагательные и первое существительное; дальше слова не меняются («директора по развитию»).
 * Первая буква становится строчной: должность стоит в середине фразы «в лице ...».
 */
[[nodiscard]] std::string post_genitive(std::string_view post);

/// Должность из реестра заглавными буквами в обычном виде: «ГЕНЕРАЛЬНЫЙ ДИРЕКТОР» -> «Генеральный директор».
[[nodiscard]] std::string normalize_post(std::string_view post);

/// ФИО заглавными буквами («ИВАНОВ ИВАН») в обычном виде («Иванов Иван»), лишние пробелы убраны.
[[nodiscard]] std::string normalize_full_name(std::string_view full_name);

/// Подпись «И. И. Иванов» из «Иванов Иван Иванович»; без имени - только фамилия.
[[nodiscard]] std::string initials_first(std::string_view full_name);

} // namespace names
