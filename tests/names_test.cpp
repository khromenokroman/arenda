#include "names.hpp"

#include <gtest/gtest.h>

#include <string>
#include <vector>

using namespace names;

namespace {

struct Case {
    std::string input;
    std::string expected;
    char gender = 0;
};

} // namespace

/**
 * @brief Родительный падеж ФИО: типы фамилий, имён и отчеств, пол по отчеству или явно.
 */
TEST(Names, FullNameGenitive) {
    std::vector<Case> const cases = {
        {"Иванов Иван Иванович", "Иванова Ивана Ивановича"},
        {"Пузыревский Виктор Вацлавович", "Пузыревского Виктора Вацлавовича"},
        {"Иванова Анна Сергеевна", "Ивановой Анны Сергеевны"},
        {"Шевчук Ольга Петровна", "Шевчук Ольги Петровны"},
        {"Шевчук Андрей Игоревич", "Шевчука Андрея Игоревича"},
        {"Толстой Лев Николаевич", "Толстого Льва Николаевича"},
        {"Толстая Мария Львовна", "Толстой Марии Львовны"},
        {"Черных Игорь Ильич", "Черных Игоря Ильича"},
        {"Глинка Никита Ильич", "Глинки Никиты Ильича"},
        {"Гоголь Николай Васильевич", "Гоголя Николая Васильевича"},
        {"Крайний Илья Петрович", "Крайнего Ильи Петровича"},
        {"Римский-Корсаков Николай Андреевич", "Римского-Корсакова Николая Андреевича"},
        {"Шевченко Любовь Ивановна", "Шевченко Любови Ивановны"},
        {"Мамедов Али Гусейн оглы", "Мамедова Али Гусейн оглы"},
        {"ИВАНОВ ИВАН ИВАНОВИЧ", "Иванова Ивана Ивановича"},
        {"Сидоров Пётр Павлович", "Сидорова Петра Павловича"},
        {"Петрова Анна", "Петровой Анны", 'f'},
        {"Петров Павел", "Петрова Павла", 'm'},
    };
    for (auto const &c : cases) {
        auto const got = full_name_genitive(c.input, c.gender);
        EXPECT_TRUE(got == c.expected) << "ФИО: " << c.input << ", пол: " << (c.gender == 0 ? '?' : c.gender) << "\n  ожидалось: " << c.expected
                                       << "\n  получено:  " << got;
    }
}

/**
 * @brief Пол по отчеству.
 */
TEST(Names, GenderByPatronymic) {
    EXPECT_EQ(gender_by_patronymic("Иванов Иван Иванович"), 'm');
    EXPECT_EQ(gender_by_patronymic("Иванова Анна Сергеевна"), 'f');
    EXPECT_EQ(gender_by_patronymic("Мамедов Али Гусейн оглы"), 'm');
    EXPECT_EQ(gender_by_patronymic("Алиева Лейла Гасан кызы"), 'f');
    EXPECT_EQ(gender_by_patronymic("Иванов Иван"), 0) << "без отчества пол не определить";
}

/**
 * @brief Должность: прилагательные и первое существительное склоняются, первая буква строчная.
 */
TEST(Names, PostGenitive) {
    std::vector<Case> const cases = {
        {"Директор", "директора"},
        {"Генеральный директор", "генерального директора"},
        {"генеральный директор", "генерального директора"},
        {"Председатель правления", "председателя правления"},
        {"Управляющий", "управляющего"},
        {"Исполнительный директор", "исполнительного директора"},
        {"Директор по развитию", "директора по развитию"},
        {"Президент", "президента"},
        {"Исполняющий обязанности директора", "исполняющего обязанности директора"},
    };
    for (auto const &c : cases) {
        auto const got = post_genitive(c.input);
        EXPECT_TRUE(got == c.expected) << "должность: " << c.input << "\n  ожидалось: " << c.expected << "\n  получено:  " << got;
    }
}

/**
 * @brief Должность из реестра заглавными буквами приводится к обычному виду; обычная не меняется.
 */
TEST(Names, NormalizePost) {
    EXPECT_EQ(normalize_post("ГЕНЕРАЛЬНЫЙ ДИРЕКТОР"), "Генеральный директор");
    EXPECT_EQ(normalize_post("Генеральный директор ООО"), "Генеральный директор ООО");
    EXPECT_EQ(normalize_post(""), "");
}

/**
 * @brief Подпись: инициалы перед фамилией.
 */
TEST(Names, InitialsFirst) {
    EXPECT_EQ(initials_first("Пузыревский Виктор Вацлавович"), "В. В. Пузыревский");
    EXPECT_EQ(initials_first("  Иванова   анна  "), "А. Иванова");
    EXPECT_EQ(initials_first("Иванов"), "Иванов");
    EXPECT_EQ(initials_first("ИВАНОВ ИВАН ИВАНОВИЧ"), "И. И. Иванов");
    EXPECT_EQ(initials_first(""), "");
}

